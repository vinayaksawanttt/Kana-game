import fs from "node:fs";
import path from "node:path";
import type { BookDetail } from "../src/data/books";

const BOOK_IDS = ["genki-1", "genki-2", "mnn-1", "mnn-2"] as const;

function cleanSpokenText(raw: string): string {
  return raw
    .replace(/[［\[][^\]］]*[］\]]/g, "")
    .replace(/\{([^|{}]+)\|([^{}]+)\}/g, "$1")
    .replace(/^[A-Za-zＡ-Ｚａ-ｚ０-９\u3040-\u30ff\u4e00-\u9faf・\s]+:\s*/u, "")
    .replace(/\s+/g, " ")
    .trim();
}

function main() {
  const map: Record<string, string> = {};
  let totalFiles = 0;

  for (const bookId of BOOK_IDS) {
    const jsonPath = path.join(process.cwd(), "public/data/v1/books", `${bookId}.json`);
    if (!fs.existsSync(jsonPath)) continue;

    const book = JSON.parse(fs.readFileSync(jsonPath, "utf8")) as BookDetail;
    let bookFiles = 0;

    for (const lesson of book.lessons || []) {
      for (const scene of lesson.dialogues || []) {
        const sceneNum = (scene.sceneNumber || "i").toLowerCase();
        for (let idx = 0; idx < (scene.lines || []).length; idx++) {
          const line = scene.lines[idx];
          const relAudio =
            line.audioSrc ||
            `/audio/books/dialogues/${bookId}/l${lesson.lessonNumber}-scene-${sceneNum}-${idx}.opus`;
          const absAudio = path.join(process.cwd(), "public", relAudio.replace(/^\/+/, ""));
          if (!fs.existsSync(absAudio)) continue;

          bookFiles++;
          totalFiles++;

          map[relAudio] = relAudio;

          const namespacedKey = `${bookId}:l${lesson.lessonNumber}-scene-${sceneNum}-${idx}`;
          map[namespacedKey] = relAudio;

          const shortKey = `l${lesson.lessonNumber}-scene-${sceneNum}-${idx}`;
          if (!map[shortKey]) {
            map[shortKey] = relAudio;
          }

          const cleaned = cleanSpokenText(line.ja || "");
          if (cleaned && !map[cleaned]) {
            map[cleaned] = relAudio;
          }
        }
      }
    }

    console.log(`[${bookId}] indexed ${bookFiles} dialogue .opus files`);
  }

  const outPath = path.join(process.cwd(), "src/data/book-dialogues-audio.generated.ts");
  const content = `// AUTO-GENERATED BY scripts/sync-book-dialogue-audio-manifest.ts — DO NOT EDIT MANUALLY

export const STATIC_BOOK_DIALOGUE_AUDIO_MAP: Record<string, string> = ${JSON.stringify(
    map,
    null,
    2
  )};
`;
  fs.writeFileSync(outPath, content, "utf8");
  console.log(
    `Generated src/data/book-dialogues-audio.generated.ts (${Object.keys(map).length} entries across ${totalFiles} files)`
  );
}

main();
