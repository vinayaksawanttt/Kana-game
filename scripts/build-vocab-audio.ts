async function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function synthesizeFile(tts: MsEdgeTTS, text: string, targetFile: string): Promise<void> {
  const maxRetries = 3;
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    try {
      await new Promise<void>((resolve, reject) => {
        const { audioStream } = tts.toStream(text, { rate: SPEECH_RATE });
        const out = fs.createWriteStream(targetFile);

        audioStream.pipe(out);
        out.on("finish", () => resolve());
        out.on("error", (err) => {
          fs.rmSync(targetFile, { force: true });
          reject(err);
        });
        audioStream.on("error", (err) => {
          fs.rmSync(targetFile, { force: true });
          reject(err);
        });
      });

      const stat = fs.statSync(targetFile);
      if (stat.size > 0) {
        return;
      }
      throw new Error(`Generated vocab audio file was empty: ${targetFile}`);
    } catch (err) {
      fs.rmSync(targetFile, { force: true });
      if (attempt === maxRetries) {
        throw err;
      }
      console.warn(`[Retry ${attempt}/${maxRetries}] Failed for "${text}": ${(err as Error).message}`);
      await sleep(500 * attempt);
    }
  }
}

function writeAudioManifest(): void {
  const readingsFiles = fs.existsSync(READINGS_AUDIO_DIR)
    ? fs
        .readdirSync(READINGS_AUDIO_DIR)
        .filter((f) => f.endsWith(".mp3"))
        .map((f) => decodeURIComponent(f.slice(0, -4)))
        .sort()
    : [];

  const vocabFiles = fs.existsSync(VOCAB_AUDIO_DIR)
    ? fs
        .readdirSync(VOCAB_AUDIO_DIR)
        .filter((f) => f.endsWith(".mp3"))
        .map((f) => decodeURIComponent(f.slice(0, -4)))
        .sort()
    : [];

  const content = `// AUTO-GENERATED BY scripts/build-vocab-audio.ts — DO NOT EDIT MANUALLY

export const STATIC_VOCAB_AUDIO = new Set<string>(${JSON.stringify(vocabFiles, null, 2)});

export const STATIC_READING_AUDIO = new Set<string>(${JSON.stringify(readingsFiles, null, 2)});
`;

  fs.writeFileSync(MANIFEST_OUTPUT_FILE, content, "utf8");
  console.log(
    `[Audio Manifest] Wrote ${vocabFiles.length} vocab clips + ${readingsFiles.length} reading clips -> src/data/audio-manifest.generated.ts`
  );
}

export async function buildVocabAudio(): Promise<void> {
  if (!fs.existsSync(VOCAB_AUDIO_DIR)) {
    fs.mkdirSync(VOCAB_AUDIO_DIR, { recursive: true });
  }

  const args = process.argv.slice(2);
  const dryRun = args.includes("--dry-run");
  const manifestOnly = args.includes("--manifest-only");
  const limitArg = args.find((a) => a.startsWith("--limit="));
  const maxTotalVocabClips = limitArg
    ? parseInt(limitArg.split("=")[1], 10)
    : DEFAULT_MAX_NEW_CLIPS;

  if (manifestOnly) {
    writeAudioManifest();
    return;
  }

  // Existing single-mora kana sounds and existing kanji readings
  const kanaSet = new Set(getUniqueKanaSounds().map((s) => katakanaToHiragana(s.sampleChar)));
  const existingReadings = new Set(
    fs.existsSync(READINGS_AUDIO_DIR)
      ? fs
          .readdirSync(READINGS_AUDIO_DIR)
          .filter((f) => f.endsWith(".mp3"))
          .map((f) => decodeURIComponent(f.slice(0, -4)))
      : []
  );

  // Collect ~250 core signature readings
  const selectedReadings = new Set<string>();

  for (const sig of SIGNATURE_READINGS) {
    const clean = katakanaToHiragana(sig.trim());
    if (clean && !kanaSet.has(clean) && !existingReadings.has(clean)) {
      selectedReadings.add(clean);
    }
  }

  // Load Shiritori words and pick top native Kanji/Hiragana words per starting kana
  const shiritoriWordsPath = path.resolve(process.cwd(), "public/data/v1/shiritori/words.json");
  if (fs.existsSync(shiritoriWordsPath)) {
    const words = JSON.parse(fs.readFileSync(shiritoriWordsPath, "utf8")) as Array<{
      word: string;
      kana: string;
      meaning: string;
      jlpt: number;
      startKana: string;
      endKana: string;
    }>;

    // Group eligible words by startKana so every starting sound in Shiritori has static neural clips
    const byStart = new Map<string, typeof words>();
    for (const w of words) {
      if (w.endKana === "ん") continue;
      if (!w.meaning || w.meaning === "valid noun") continue;
      // Skip pure katakana loanwords
      if (/^[\u30A0-\u30FFー]+$/.test(w.word)) continue;

      const cleanKana = katakanaToHiragana(w.kana.trim());
      if (cleanKana.length < 2 || cleanKana.length > 5) continue;
      if (kanaSet.has(cleanKana) || existingReadings.has(cleanKana)) continue;

      const list = byStart.get(w.startKana) ?? [];
      list.push(w);
      byStart.set(w.startKana, list);
    }

    // Sort each bucket by JLPT level (N5=5 first, then N4=4, N3=3) and shorter length
    for (const [, list] of byStart) {
      list.sort((a, b) => b.jlpt - a.jlpt || a.kana.length - b.kana.length);
    }

    // Round-robin pick across all starting kana buckets until we reach maxTotalVocabClips
    let round = 0;
    while (selectedReadings.size < maxTotalVocabClips && round < 10) {
      let addedInRound = false;
      for (const [, list] of byStart) {
        if (selectedReadings.size >= maxTotalVocabClips) break;
        const candidate = list[round];
        if (candidate) {
          const clean = katakanaToHiragana(candidate.kana.trim());
          if (!selectedReadings.has(clean)) {
            selectedReadings.add(clean);
            addedInRound = true;
          }
        }
      }
      if (!addedInRound) break;
      round++;
    }
  }

  const candidates = Array.from(selectedReadings).slice(0, maxTotalVocabClips);
  const toSynthesize: string[] = [];
  let cachedCount = 0;

  for (const reading of candidates) {
    const filePath = path.join(VOCAB_AUDIO_DIR, `${reading}.mp3`);
    if (fs.existsSync(filePath) && fs.statSync(filePath).size > 0) {
      cachedCount++;
    } else {
      toSynthesize.push(reading);
    }
  }

  console.log(
    `[Vocab Audio Pipeline] Target: ${candidates.length} signature words (${cachedCount} cached, ${toSynthesize.length} to synthesize).`
  );

  if (dryRun) {
    console.log("[Vocab Audio Pipeline] Dry run complete. Sample words:", toSynthesize.slice(0, 15));
    writeAudioManifest();
    return;
  }

  if (toSynthesize.length > 0) {
    const tts = new MsEdgeTTS();
    await tts.setMetadata(VOICE, OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);

    for (let i = 0; i < toSynthesize.length; i++) {
      const reading = toSynthesize[i];
      const targetFile = path.join(VOCAB_AUDIO_DIR, `${reading}.mp3`);

      process.stdout.write(`[${i + 1}/${toSynthesize.length}] Synthesizing "${reading}"... `);
      await synthesizeFile(tts, reading, targetFile);
      process.stdout.write(`Done (${fs.statSync(targetFile).size} bytes)\n`);

      await sleep(50);
    }
  }

  writeAudioManifest();
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  buildVocabAudio().catch((err) => {
    console.error("[Vocab Audio Pipeline Error]", err);
    process.exit(1);
  });
}
