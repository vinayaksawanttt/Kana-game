import fs from "node:fs";
import path from "node:path";
import { MsEdgeTTS, OUTPUT_FORMAT } from "msedge-tts";
import { cleanGrammarTitleForAudio } from "../src/engine/audio";

const GRAMMAR_INDEX_PATH = path.resolve(process.cwd(), "public/data/v1/grammar/index.json");
const GRAMMAR_AUDIO_DIR = path.resolve(process.cwd(), "public/audio/grammar");
const MANIFEST_FILE = path.resolve(process.cwd(), "src/data/audio-manifest.generated.ts");

const VOICE = "ja-JP-NanamiNeural";
const SPEECH_RATE = "-5%";
const CONCURRENCY = 6;

interface GrammarPointEntry {
  id: string;
  slug: string;
  level: string;
  title: string;
  pattern: string;
  romaji: string;
  meaning: string;
}

interface GrammarIndexData {
  points: GrammarPointEntry[];
}

async function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function synthesizeFile(
  tts: MsEdgeTTS,
  text: string,
  targetFile: string
): Promise<void> {
  const maxRetries = 3;
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    try {
      await new Promise<void>((resolve, reject) => {
        const { audioStream } = tts.toStream(text, { rate: SPEECH_RATE });
        const out = fs.createWriteStream(targetFile);

        audioStream.pipe(out);
        out.on("finish", () => resolve());
        out.on("error", (err) => {
          fs.rmSync(targetFile, { force: true });
          reject(err);
        });
        audioStream.on("error", (err) => {
          fs.rmSync(targetFile, { force: true });
          reject(err);
        });
      });

      const stat = fs.statSync(targetFile);
      if (stat.size > 0) {
        return;
      }
      throw new Error(`Generated audio file was empty: ${targetFile}`);
    } catch (err) {
      fs.rmSync(targetFile, { force: true });
      if (attempt === maxRetries) {
        throw err;
      }
      await sleep(300 * attempt);
    }
  }
}

export function updateAudioManifest(points: GrammarPointEntry[]): void {
  // Read existing manifest file to preserve STATIC_VOCAB_AUDIO and STATIC_READING_AUDIO
  let existingContent = "";
  if (fs.existsSync(MANIFEST_FILE)) {
    existingContent = fs.readFileSync(MANIFEST_FILE, "utf8");
  }

  const audioMap: Record<string, string> = {};
  for (const point of points) {
    const targetFile = path.join(GRAMMAR_AUDIO_DIR, `${point.id}.mp3`);
    if (fs.existsSync(targetFile) && fs.statSync(targetFile).size > 0) {
      const audioUrl = `/audio/grammar/${point.id}.mp3`;
      audioMap[point.id] = audioUrl;
      audioMap[point.pattern] = audioUrl;
      const clean = cleanGrammarTitleForAudio(point.pattern);
      if (clean) {
        audioMap[clean] = audioUrl;
      }
    }
  }

  // Preserve existing vocab, reading, and listening exports
  const vocabMatch = existingContent.match(/export const STATIC_VOCAB_AUDIO = new Set<string>\(([\s\S]*?)\);/);
  const readingMatch = existingContent.match(/export const STATIC_READING_AUDIO = new Set<string>\(([\s\S]*?)\);/);
  const listeningMatch = existingContent.match(/export const STATIC_LISTENING_SENTENCE_AUDIO_MAP: Record<string, string> = [\s\S]*?;/);

  const vocabBlock = vocabMatch ? vocabMatch[0] : `export const STATIC_VOCAB_AUDIO = new Set<string>([]);`;
  const readingBlock = readingMatch ? readingMatch[0] : `export const STATIC_READING_AUDIO = new Set<string>([]);`;
  const listeningBlock = listeningMatch ? `\n${listeningMatch[0]}\n` : "";

  const newContent = `// AUTO-GENERATED BY scripts/build-grammar-audio.ts & scripts/build-vocab-audio.ts — DO NOT EDIT MANUALLY

${vocabBlock}

${readingBlock}

export const STATIC_GRAMMAR_AUDIO_MAP: Record<string, string> = ${JSON.stringify(audioMap, null, 2)};
${listeningBlock}`;

  fs.writeFileSync(MANIFEST_FILE, newContent, "utf8");
  console.log(`[Audio Manifest] Updated STATIC_GRAMMAR_AUDIO_MAP with ${Object.keys(audioMap).length} lookup keys.`);
}

export async function buildGrammarAudio(): Promise<void> {
  if (!fs.existsSync(GRAMMAR_INDEX_PATH)) {
    throw new Error(`Grammar index not found at ${GRAMMAR_INDEX_PATH}`);
  }

  const data = JSON.parse(fs.readFileSync(GRAMMAR_INDEX_PATH, "utf8")) as GrammarIndexData;
  const points = data.points;

  console.log(`[Grammar Audio] Total grammar points to process: ${points.length}`);

  // Ensure directories exist
  const levels = ["N5", "N4", "N3", "N2", "N1"];
  for (const level of levels) {
    const dir = path.join(GRAMMAR_AUDIO_DIR, level);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
  }

  const tasks: Array<{ point: GrammarPointEntry; ttsText: string; targetFile: string }> = [];
  let existingCount = 0;

  for (const point of points) {
    const targetFile = path.join(GRAMMAR_AUDIO_DIR, `${point.id}.mp3`);
    if (fs.existsSync(targetFile) && fs.statSync(targetFile).size > 0) {
      existingCount++;
    } else {
      const ttsText = cleanGrammarTitleForAudio(point.pattern);
      tasks.push({ point, ttsText, targetFile });
    }
  }

  console.log(`[Grammar Audio] ${existingCount} already generated, ${tasks.length} to synthesize.`);

  if (tasks.length > 0) {
    const tts = new MsEdgeTTS();
    await tts.setMetadata(VOICE, OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);

    let completed = 0;
    const startTime = Date.now();

    // Worker pool with concurrency
    async function worker(index: number) {
      while (tasks.length > 0) {
        const item = tasks.shift();
        if (!item) break;

        await synthesizeFile(tts, item.ttsText, item.targetFile);
        completed++;

        if (completed % 25 === 0 || completed === tasks.length) {
          const elapsedSec = ((Date.now() - startTime) / 1000).toFixed(1);
          console.log(`[Grammar Audio] Progress: ${completed}/${tasks.length + existingCount} clips (${elapsedSec}s elapsed)...`);
        }
      }
    }

    const workers = Array.from({ length: CONCURRENCY }, (_, i) => worker(i));
    await Promise.all(workers);

    const totalSec = ((Date.now() - startTime) / 1000).toFixed(1);
    console.log(`[Grammar Audio] Completed synthesizing ${completed} clips in ${totalSec}s.`);
  }

  updateAudioManifest(points);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  buildGrammarAudio().catch((err) => {
    console.error("[Grammar Audio Error]", err);
    process.exit(1);
  });
}
